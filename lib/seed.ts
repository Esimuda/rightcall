type PredictionInput = {
  id: string;
  sourceId: string;
  sourceName: string;
  category: string;
  event: string;
  conditions: string[];
  pick: string;
  statedConfidence: number;
  outcome: "hit" | "miss";
  lockedAt: string;
  resolvedAt: string;
  note: string;
};

function prediction(input: PredictionInput): Observation {
  const result = input.outcome === "hit" ? 1 : 0;
  return {
    id: input.id,
    schema: SCHEMA,
    kind: "prediction_outcome",
    sourceId: input.sourceId,
    sourceName: input.sourceName,
    category: input.category,
    event: input.event,
    conditions: input.conditions,
    pick: input.pick,
    statedConfidence: input.statedConfidence,
    outcome: input.outcome,
    bookProbability: null,
    chainProbability: null,
    gapPp: null,
    gapSide: null,
    disagreementOutcome: null,
    lockedAt: input.lockedAt,
    resolvedAt: input.resolvedAt,
    lockedCheckpoint: null,
    resolvedCheckpoint: null,
    provenance: "seed",
    note: `${input.note} Calibration: stated ${(input.statedConfidence * 100).toFixed(0)}% versus result ${result}. This is the call and the result, not a label about the person.`,
  };
}

type OddsInput = {
  id: string;
  event: string;
  book: number;
  chain: number;
  outcome: "book_correct" | "chain_correct";
  spot: "spot-under" | "spot-over";
  lockedAt: string;
  resolvedAt: string;
};

function odds(input: OddsInput): Observation {
  const gapPp = Math.round((input.book - input.chain) * 100);
  const winner = input.outcome === "chain_correct" ? "the chain side" : "the book side";
  return {
    id: input.id,
    schema: SCHEMA,
    kind: "odds_disagreement",
    sourceId: "odds-desk",
    sourceName: "Odds desk",
    category: "BTC expiry",
    event: input.event,
    conditions: ["btc", "5m", "book-richer", input.spot],
    pick: null,
    statedConfidence: null,
    outcome: null,
    bookProbability: input.book,
    chainProbability: input.chain,
    gapPp,
    gapSide: gapPp > 0 ? "book_richer" : gapPp < 0 ? "chain_richer" : "even",
    disagreementOutcome: input.outcome,
    lockedAt: input.lockedAt,
    resolvedAt: input.resolvedAt,
    lockedCheckpoint: null,
    resolvedCheckpoint: null,
    provenance: "seed",
    note: `Seeded book implied ${(input.book * 100).toFixed(0)}% and a recorded chain quote of ${(input.chain * 100).toFixed(0)}% on a 5-minute BTC expiry, with spot ${input.spot === "spot-under" ? "under" : "over"} the reference strike. ${winner} matched the settlement. Book numbers are seed. They are not a Tatum sportsbook feed.`,
  };
}

